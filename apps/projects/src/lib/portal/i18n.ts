export const DICTIONARIES: Readonly<Record<Locale, Readonly<Record<PortalKey, string>>>> = { en: EN, es: ES };

export function t(l: Locale, key: PortalKey, vars: Readonly<Record<string, string | number>> = {}): string {
  const s = DICTIONARIES[l]?.[key] ?? EN[key];
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function kindLabel(l: Locale, k: QueueKind): string {
  return t(l, `kind.${k}` as PortalKey);
}

export function parseLocale(v: string | null | undefined): Locale {
  return v === 'es' ? 'es' : 'en';
}
