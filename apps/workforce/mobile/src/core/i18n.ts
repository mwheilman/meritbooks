export const STRINGS: Readonly<Record<Lang, Readonly<Record<StringKey, string>>>> = { en, es };

export function translate(lang: Lang, key: StringKey, vars: Readonly<Record<string, string | number>> = {}): string {
  const s = STRINGS[lang][key] ?? STRINGS.en[key];
  return s.replace(/\{(\w+)\}/g, (_m, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function placeholders(s: string): string[] {
  return [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1] ?? '').sort();
}

/** Spanish when the phone's first language is Spanish, else English. */
export function langFromLocale(tag: string | null | undefined): Lang {
  return (tag ?? '').toLowerCase().startsWith('es') ? 'es' : 'en';
}
